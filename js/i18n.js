let currentLang = 'en';

function setLanguage(lang) {
  currentLang = lang;
  const dict = i18nData[lang];
  if (!dict) return;

  // Update text elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Toggle active pill UI
  const enPill = document.getElementById('lang-en');
  const hiPill = document.getElementById('lang-hi');
  if (enPill) enPill.classList.toggle('active', lang === 'en');
  if (hiPill) hiPill.classList.toggle('active', lang === 'hi');
  
  localStorage.setItem('ardya_lang', lang);
}

// Auto-restore saved language
document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('ardya_lang');
  if (saved) setLanguage(saved);
  
  document.getElementById('lang-en')?.addEventListener('click', (e) => {
    e.stopPropagation();
    setLanguage('en');
  });
  document.getElementById('lang-hi')?.addEventListener('click', (e) => {
    e.stopPropagation();
    setLanguage('hi');
  });
  document.getElementById('lang-toggle-btn')?.addEventListener('click', () => {
    setLanguage(currentLang === 'en' ? 'hi' : 'en');
  });
});
